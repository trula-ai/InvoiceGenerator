/**
 * Due-date automation.
 *
 * `runDailyChecks` promotes overdue invoices, raises due-soon / due-today /
 * overdue notifications, runs the reminder schedule below and finally emails
 * the business's own users a "notify mail" summarising what was sent and what
 * is still pending. It is idempotent: every automatic reminder is recorded in
 * `invoice_reminders` with a stage key, so re-running never sends the same
 * reminder twice.
 *
 * Schedule (per business, editable in Settings > Payment reminders):
 * - before the due date: one email on each day listed in `reminderSchedule`
 *   (default "7,3,1": a week before, three days before, the day before).
 *   If a run is missed, the next run sends the latest pending step only.
 * - "due today": once, on the due date.
 * - "overdue" (pending payment): every `reminderOverdueEveryDays` days after.
 * Clients can opt out with `clients.autoReminders = false`; manual sends from
 * the invoice or client pages are never blocked by that flag.
 *
 * Triggered two ways:
 * - `GET /api/cron/due-reminders` (any daily scheduler) runs it for every
 *   business.
 * - The dashboard layout calls `maybeRunDailyChecks` after each response for
 *   the signed-in business, throttled to once an hour per server process, so
 *   local and self-hosted setups work without a scheduler.
 */

export interface DueReminderSummary {
  businessId: string;
  date: string;
  sent: number;
  failed: number;
  skipped: number;
  notified: number;
  /** Number of business users who received the notify mail. */
  ownerNotified: number;
  /** Invoices generated by recurring schedules in this run. */
  recurringCreated: number;
}

// The pure stage-selection logic lives in lib/reminder-schedule.ts so it can be
// tested without the email and PDF stack; re-exported here for callers.
export { reminderStageFor };
export type { ReminderPlan, ReminderScheduleSettings };

export async function loadReminderSettings(businessId: string): Promise<ReminderScheduleSettings | null> {
  const [row] = await db
    .select({
      remindersEnabled: businesses.remindersEnabled,
      reminderSchedule: businesses.reminderSchedule,
      reminderOverdueEveryDays: businesses.reminderOverdueEveryDays,
      notifyOwner: businesses.notifyOwner,
    })
    .from(businesses)
    .where(eq(businesses.id, businessId))
    .limit(1);
  if (!row) return null;
  return {
    remindersEnabled: row.remindersEnabled,
    reminderOffsets: parseReminderSchedule(row.reminderSchedule),
    reminderOverdueEveryDays: row.reminderOverdueEveryDays,
    notifyOwner: row.notifyOwner,
  };
}

interface PayableRow {
  id: string;
  invoiceNumber: string;
  dueDate: string;
  balanceDue: string;
  currency: string;
  lastReminderAt: Date | null;
  clientName: string;
  email: string | null;
  autoReminders: boolean;
}

async function listPayableInvoices(businessId: string): Promise<PayableRow[]> {
  return db
    .select({
      id: invoices.id,
      invoiceNumber: invoices.invoiceNumber,
      dueDate: invoices.dueDate,
      balanceDue: invoices.balanceDue,
      currency: invoices.currency,
      lastReminderAt: invoices.lastReminderAt,
      clientName: clients.name,
      email: clients.email,
      autoReminders: clients.autoReminders,
    })
    .from(invoices)
    .innerJoin(clients, eq(clients.id, invoices.clientId))
    .where(
      and(eq(invoices.businessId, businessId), eq(invoices.documentKind, "invoice"), inArray(invoices.status, PAYABLE_STATUSES), sql`${invoices.balanceDue} > 0`),
    )
    .orderBy(invoices.dueDate, invoices.issueDate);
}

function pendingLabel(dueDate: string, today: string): { label: string; overdue: boolean } {
  const days = daysBetweenIso(today, dueDate);
  if (days === 0) return { label: "Due today", overdue: false };
  if (days > 0) return { label: `Due in ${days} day${days === 1 ? "" : "s"}`, overdue: false };
  return { label: `${-days} day${days === -1 ? "" : "s"} overdue`, overdue: true };
}

interface ScheduleRun extends Omit<DueReminderSummary, "notified" | "ownerNotified" | "recurringCreated"> {
  events: OwnerNotifyEvent[];
  pending: OwnerNotifyPending[];
  pendingTotals: string[];
}

/** Sends every reminder the schedule says is owed today for one business. */
export async function runReminderSchedule(businessId: string, today = todayIso(), settings?: ReminderScheduleSettings | null): Promise<ScheduleRun> {
  const run: ScheduleRun = { businessId, date: today, sent: 0, failed: 0, skipped: 0, events: [], pending: [], pendingTotals: [] };
  const cfg = settings === undefined ? await loadReminderSettings(businessId) : settings;
  if (!cfg?.remindersEnabled) return run;

  const rows = await listPayableInvoices(businessId);

  const totals = new Map<string, ReturnType<typeof D>>();
  for (const inv of rows) {
    totals.set(inv.currency, (totals.get(inv.currency) ?? D(0)).plus(D(inv.balanceDue)));
    const { label, overdue } = pendingLabel(inv.dueDate, today);
    run.pending.push({
      invoiceNumber: inv.invoiceNumber,
      clientName: inv.clientName,
      dueDate: formatDate(inv.dueDate),
      balanceFormatted: formatCurrency(inv.balanceDue, inv.currency),
      statusLabel: label,
      overdue,
    });
  }
  run.pendingTotals = [...totals.entries()].map(([currency, amount]) => formatCurrency(toMoney(amount), currency));

  for (const inv of rows) {
    const plan = reminderStageFor(inv.dueDate, today, cfg);
    if (!plan) continue;

    const email = inv.email?.trim();
    if (!inv.autoReminders || !email) {
      run.skipped += 1;
      continue;
    }

    const [done] = await db
      .select({ id: invoiceReminders.id })
      .from(invoiceReminders)
      .where(and(eq(invoiceReminders.invoiceId, inv.id), eq(invoiceReminders.stageKey, plan.key)))
      .limit(1);
    if (done) {
      run.skipped += 1;
      continue;
    }

    // A reminder already went out by hand today: count this stage as covered.
    if (inv.lastReminderAt && format(inv.lastReminderAt, "yyyy-MM-dd") === today) {
      await db
        .insert(invoiceReminders)
        .values({ businessId, invoiceId: inv.id, stage: plan.stage, stageKey: plan.key, toEmail: email })
        .onConflictDoNothing();
      run.skipped += 1;
      continue;
    }

    const event: OwnerNotifyEvent = {
      invoiceNumber: inv.invoiceNumber,
      clientName: inv.clientName,
      to: email,
      dueDate: formatDate(inv.dueDate),
      balanceFormatted: formatCurrency(inv.balanceDue, inv.currency),
      stageLabel: plan.label,
      ok: false,
    };
    try {
      const result = await sendReminderEmail(businessId, inv.id);
      await db
        .insert(invoiceReminders)
        .values({ businessId, invoiceId: inv.id, stage: plan.stage, stageKey: plan.key, toEmail: result.to })
        .onConflictDoNothing();
      run.sent += 1;
      event.to = result.to;
      event.ok = true;
    } catch (error) {
      run.failed += 1;
      event.error = error instanceof Error ? error.message : String(error);
      console.error(`[due-reminders] invoice ${inv.id}:`, event.error);
    }
    run.events.push(event);
  }
  return run;
}

export async function runDailyChecks(businessId: string): Promise<DueReminderSummary> {
  const today = todayIso();
  const settings = await loadReminderSettings(businessId);
  // Recurring schedules first, so an invoice generated today is included in the checks below.
  const recurring = await runRecurringProfiles(businessId, today);
  await syncOverdueStatuses(businessId);
  const dueSoonDays = settings?.reminderOffsets[0] ?? 3;
  const notified = await syncPaymentNotifications(businessId, today, dueSoonDays);
  const { events, pending, pendingTotals, ...reminders } = await runReminderSchedule(businessId, today, settings);

  let ownerNotified = 0;
  if (settings?.notifyOwner && events.length > 0) {
    ownerNotified = await sendOwnerNotifyEmail(businessId, { date: today, events, pending, pendingTotals });
  }
  return { ...reminders, notified, ownerNotified, recurringCreated: recurring.created };
}

export async function runDailyChecksForAllBusinesses(): Promise<DueReminderSummary[]> {
  const rows = await db.select({ id: businesses.id }).from(businesses);
  const results: DueReminderSummary[] = [];
  for (const row of rows) results.push(await runDailyChecks(row.id));
  return results;
}

const THROTTLE_MS = 60 * 60 * 1000;
const globalForChecks = globalThis as typeof globalThis & { __invoiceGeneratorDailyChecks?: Map<string, number> };
const lastRun = (globalForChecks.__invoiceGeneratorDailyChecks ??= new Map<string, number>());

/** Runs the daily checks for one business at most once an hour per process. Never throws. */
export async function maybeRunDailyChecks(businessId: string): Promise<DueReminderSummary | null> {
  const now = Date.now();
  if (now - (lastRun.get(businessId) ?? 0) < THROTTLE_MS) return null;
  lastRun.set(businessId, now);
  try {
    return await runDailyChecks(businessId);
  } catch (error) {
    lastRun.delete(businessId);
    console.error("[due-reminders] daily checks failed:", error instanceof Error ? error.message : error);
    return null;
  }
}
